#!/usr/bin/env python3
"""Embed binary files as C arrays.

  embed_bin.py INPUT SYMBOL OUT.c
  embed_bin.py --multi OUT.c INPUT SYMBOL [INPUT SYMBOL ...]   (several in one file)

Each array comes with SYMBOL_len; an empty input gives a length of 0.
"""
import sys


def emit(f, path, sym):
    data = open(path, 'rb').read()
    f.write(f'const unsigned int {sym}_len = {len(data)};\n')
    f.write(f'const unsigned char {sym}[] = {{\n')
    for i in range(0, len(data), 24):
        f.write('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
    if not data:
        f.write('  0\n')
    f.write('};\n')


if sys.argv[1] == '--multi':
    out, rest = sys.argv[2], sys.argv[3:]
    pairs = list(zip(rest[0::2], rest[1::2]))
else:
    out, pairs = sys.argv[3], [(sys.argv[1], sys.argv[2])]
with open(out, 'w') as f:
    names = ', '.join(p.split('/')[-1] for p, _ in pairs)
    f.write(f'// Generated by tools/embed_bin.py from {names}. Do not edit.\n')
    for path, sym in pairs:
        emit(f, path, sym)
