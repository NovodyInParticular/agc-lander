#!/usr/bin/env python3
"""Embed a binary file as a C array: embed_bin.py INPUT SYMBOL OUT.c"""
import sys
data = open(sys.argv[1], 'rb').read()
sym = sys.argv[2]
with open(sys.argv[3], 'w') as f:
    f.write(f'// Generated by tools/embed_bin.py from {sys.argv[1].split("/")[-1]}. Do not edit.\n')
    f.write(f'const unsigned int {sym}_len = {len(data)};\n')
    f.write(f'const unsigned char {sym}[] = {{\n')
    for i in range(0, len(data), 24):
        f.write('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
