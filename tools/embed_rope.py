#!/usr/bin/env python3
"""Turn a yaYUL .bin rope image into a C source file (rope_image[], rope_image_len)."""
import sys

data = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as f:
    f.write(f'// Generated by tools/embed_rope.py from {sys.argv[1].split("/")[-1]}. Do not edit.\n')
    f.write(f'const unsigned int rope_image_len = {len(data)};\n')
    f.write('const unsigned char rope_image[] = {\n')
    for i in range(0, len(data), 16):
        f.write('  ' + ','.join(str(b) for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
