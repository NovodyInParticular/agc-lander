#!/usr/bin/env python3
"""Extract erasable-memory symbols from a yaYUL listing into a C lookup table.

Usage: gen_symbols.py LISTING OUT.c
Emits agc_symbols[] sorted by name: {name, bank, offset} with offset 0..0377.
"""
import re
import sys

entry = re.compile(r'\s*\d+,([A-Z]):\s+(\S+)\s+(E(\d),(\d{4})|(\d{4,7}))\s*$')
syms = {}
in_table = False
for line in open(sys.argv[1], errors='replace'):
    if line.startswith('Symbol Table'):
        in_table = True
        continue
    if not in_table:
        continue
    for cell in line.rstrip('\n').split('\t'):
        m = entry.match(cell)
        if not m:
            continue
        kind, name = m.group(1), m.group(2)
        if kind == 'E' and m.group(4):            # switched erasable: E<bank>,<1400-1777>
            bank, addr = int(m.group(4)), int(m.group(5), 8)
            if not 0o1400 <= addr <= 0o1777:
                continue
            syms[name] = (bank, addr - 0o1400)
        elif kind in ('E', 'C') and m.group(6):   # unswitched erasable 0000-1377 (or equate)
            addr = int(m.group(6), 8)
            if addr < 0o1400:
                syms.setdefault(name, (addr // 0o400, addr % 0o400))

with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_symbols.py from the yaYUL listing. Do not edit.\n')
    f.write('#include "agc_mem.h"\n')
    f.write(f'const AgcSymbol agc_symbols[{len(syms)}] = {{\n')
    for name in sorted(syms):
        b, o = syms[name]
        cname = name.replace('\\', '\\\\').replace('"', '\\"')
        f.write(f'  {{ "{cname}", {b}, 0{o:o} }},\n')
    f.write('};\n')
    f.write(f'const int agc_symbol_count = {len(syms)};\n')
print(f'{len(syms)} erasable symbols')
