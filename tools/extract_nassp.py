#!/usr/bin/env python3
"""Extract the LM's LGC state from a NASSP (Project Apollo for Orbiter) scenario.

Usage: extract_nassp.py SCENARIO.scn OUT.c

Writes the LGC erasable memory image, the input channel values and a few
vehicle properties as C data. NASSP is GPLv2; so is this project.
"""
import sys

lines = open(sys.argv[1], encoding='latin-1').read().splitlines()
start = next(i for i, l in enumerate(lines) if l.startswith('Eagle:ProjectApollo'))
emem, vichan, props = {}, {}, {}
in_agc = False
for l in lines[start:]:
    s = l.strip()
    if s == 'AGC_BEGIN':
        in_agc = True
        continue
    if s == 'AGC_END':
        break
    parts = s.split()
    if len(parts) != 2:
        continue
    k, v = parts
    if not in_agc:
        if k in ('DSCFUEL', 'ASCFUEL', 'DSCEMPTYMASS', 'ASCEMPTYMASS', 'MISSNTIME'):
            props[k] = float(v)
        continue
    if k.startswith('EMEM'):
        emem[int(k[4:], 8)] = int(v, 8)          # octal address, octal value
    elif k.startswith('VICHAN'):
        vichan[int(k[6:])] = int(v)               # decimal channel, decimal value
    elif k == 'VOC7':
        props['VOC7'] = int(v)

with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/extract_nassp.py from the NASSP Apollo 11 "PDI T-15m"\n')
    f.write('// scenario (Project Apollo - NASSP, GPLv2). LGC running Luminary099. Do not edit.\n')
    f.write('#include "scenario_data.h"\n')
    f.write(f'const ScenarioWord a11_pdi_erasable[{len(emem)}] = {{\n')
    for a in sorted(emem):
        f.write(f'  {{ 0{a:o}, 0{emem[a]:o} }},\n')
    f.write('};\n')
    f.write(f'const int a11_pdi_erasable_count = {len(emem)};\n')
    f.write(f'const ScenarioWord a11_pdi_channels[{len(vichan)}] = {{\n')
    for c in sorted(vichan):
        f.write(f'  {{ 0{c:o}, 0{vichan[c]:o} }},\n')
    f.write('};\n')
    f.write(f'const int a11_pdi_channel_count = {len(vichan)};\n')
    f.write(f'const int a11_pdi_superbank = 0{props.get("VOC7", 0):o};\n')
    for k in ('DSCFUEL', 'ASCFUEL', 'DSCEMPTYMASS', 'ASCEMPTYMASS'):
        f.write(f'const double a11_pdi_{k.lower()} = {props[k]!r};\n')
print(f'{len(emem)} erasable words, {len(vichan)} channels, props {props}')
